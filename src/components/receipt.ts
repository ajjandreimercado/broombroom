import { Commission, PaymentReceipt, VehicleApplication } from '../types.ts';
import { pesoWords } from './ar.ts';

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
const peso = (n: number) => `₱${Math.round(n).toLocaleString('en-PH')}`;
const date = (iso?: string) =>
  iso ? new Date(iso).toLocaleDateString('en-PH', { year: 'numeric', month: 'long', day: 'numeric' }) : '-';
const logoUrl = () => new URL(`${import.meta.env.BASE_URL}broom-broom-logo.png`, window.location.href).href;

// Opens a printable page in its own tab; the print dialog saves it as a PDF. False if pop-ups are blocked.
const openPrintable = (html: string) => {
  const win = window.open('', '_blank');
  if (!win) return false;
  win.document.open();
  win.document.write(html);
  win.document.close();
  return true;
};

